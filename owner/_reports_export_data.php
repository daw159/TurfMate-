<?php
declare(strict_types=1);

/**
 * TurfMate Export Reports: read-only data provider.
 * Included by reports-export.php and reports-download.php after owner/_init.php.
 * All SQL is scoped to the authenticated owner.
 */

function tm_x_valid_date(string $date): bool
{
    $parsed = DateTimeImmutable::createFromFormat('!Y-m-d', $date);
    return $parsed !== false && $parsed->format('Y-m-d') === $date;
}

function tm_x_period_dates(array $input): array
{
    $today = new DateTimeImmutable('today');
    $period = (string) ($input['period'] ?? 'month');
    if (!in_array($period, ['today', 'yesterday', 'week', 'month', 'year', 'custom'], true)) {
        $period = 'month';
    }

    switch ($period) {
        case 'today':
            $from = $to = $today->format('Y-m-d');
            break;
        case 'yesterday':
            $from = $to = $today->modify('-1 day')->format('Y-m-d');
            break;
        case 'week':
            $from = $today->modify('monday this week')->format('Y-m-d');
            $to = $today->format('Y-m-d');
            break;
        case 'year':
            $from = $today->format('Y-01-01');
            $to = $today->format('Y-m-d');
            break;
        case 'custom':
            $from = (string) ($input['from'] ?? '');
            $to = (string) ($input['to'] ?? '');
            if (!tm_x_valid_date($from) || !tm_x_valid_date($to)) {
                throw new InvalidArgumentException('Choose valid From and To dates.');
            }
            if ($from > $to) {
                throw new InvalidArgumentException('From date must not be after To date.');
            }
            break;
        default:
            $from = $today->format('Y-m-01');
            $to = $today->format('Y-m-d');
            $period = 'month';
            break;
    }

    $a = new DateTimeImmutable($from);
    $b = new DateTimeImmutable($to);
    if ($a->diff($b)->days > 1095) {
        throw new InvalidArgumentException('Choose a date range of three years or less.');
    }

    return [$period, $from, $to];
}

function tm_x_options(PDO $db, int $ownerId): array
{
    $stmt = $db->prepare(
        'SELECT id, name FROM facilities
         WHERE owner_id = ? AND deleted_at IS NULL ORDER BY name'
    );
    $stmt->execute([$ownerId]);
    return $stmt->fetchAll(PDO::FETCH_ASSOC);
}

function tm_x_config(array $input, array $facilities): array
{
    $types = [
        'financial' => 'Financial Summary',
        'bookings' => 'Booking Reservations',
        'payments' => 'Payments and Refunds',
        'expenses' => 'Expense History',
        'inventory' => 'Inventory Snapshot',
        'stock' => 'Stock Transactions',
        'maintenance' => 'Maintenance History',
    ];
    $type = (string) ($input['type'] ?? 'financial');
    if (!isset($types[$type])) {
        throw new InvalidArgumentException('Choose a valid report type.');
    }

    $allowed = array_map('intval', array_column($facilities, 'id'));
    $rawFacility = (string) ($input['facility_id'] ?? '0');
    if (!ctype_digit($rawFacility)) {
        throw new InvalidArgumentException('Invalid facility.');
    }
    $facilityId = (int) $rawFacility;
    if ($facilityId !== 0 && !in_array($facilityId, $allowed, true)) {
        throw new InvalidArgumentException('You do not have access to that facility.');
    }

    [$period, $from, $to] = tm_x_period_dates($input);
    return compact('type', 'types', 'facilityId', 'period', 'from', 'to');
}

function tm_x_rows(PDO $db, string $sql, array $params, int $limit): array
{
    // LIMIT is always an integer generated by the app, never user-submitted SQL.
    $stmt = $db->prepare($sql . ' LIMIT ' . max(1, min(20001, $limit)));
    $stmt->execute($params);
    return $stmt->fetchAll(PDO::FETCH_ASSOC);
}

function tm_x_scalar(PDO $db, string $sql, array $params): float
{
    $stmt = $db->prepare($sql);
    $stmt->execute($params);
    return (float) $stmt->fetchColumn();
}

/**
 * Output: ['columns' => [columnKey => label], 'rows' => [...], 'note' => ...]
 * $limit=26 for a 25-row preview; 20001 for an up-to-20000-row export.
 */
function tm_x_report(PDO $db, int $ownerId, array $config, int $limit = 26): array
{
    $type = $config['type'];
    $fid = (int) $config['facilityId'];
    $from = $config['from'];
    $to = $config['to'];
    $facilityFilter = $fid ? ' AND f.id = ?' : '';
    $byDate = [$ownerId, $from, $to];
    $byOwner = [$ownerId];
    if ($fid) {
        $byDate[] = $fid;
        $byOwner[] = $fid;
    }

    switch ($type) {
        case 'financial':
            // Amounts are intentionally separated by booking date, payment date, and expense date.
            // SUM of bookings is not joined to raw payments (would multiply booking amounts).
            $bookings = tm_x_scalar(
                $db,
                "SELECT COALESCE(SUM(b.total_amount), 0)
                 FROM bookings b
                 JOIN turfs t ON t.id = b.turf_id
                 JOIN facilities f ON f.id = t.facility_id
                 WHERE f.owner_id = ? AND f.deleted_at IS NULL
                   AND b.status IN ('confirmed','completed')
                   AND b.booking_date BETWEEN ? AND ? $facilityFilter",
                $byDate
            );
            $collected = tm_x_scalar(
                $db,
                "SELECT COALESCE(SUM(CASE WHEN p.status = 'received' THEN p.amount
                         WHEN p.status = 'refunded' THEN -p.amount ELSE 0 END), 0)
                 FROM payments p
                 JOIN bookings b ON b.id = p.booking_id
                 JOIN turfs t ON t.id = b.turf_id
                 JOIN facilities f ON f.id = t.facility_id
                 WHERE f.owner_id = ? AND f.deleted_at IS NULL
                   AND p.paid_at >= ? AND p.paid_at < DATE_ADD(?, INTERVAL 1 DAY)
                   $facilityFilter",
                $byDate
            );
            $expenses = tm_x_scalar(
                $db,
                "SELECT COALESCE(SUM(e.amount), 0)
                 FROM expenses e JOIN facilities f ON f.id = e.facility_id
                 WHERE f.owner_id = ? AND f.deleted_at IS NULL
                   AND e.expense_date BETWEEN ? AND ? $facilityFilter",
                $byDate
            );
            $values = [
                ['metric' => 'Eligible booking value (booking dates)', 'amount' => number_format($bookings, 2, '.', '')],
                ['metric' => 'Net payments collected (payment dates)', 'amount' => number_format($collected, 2, '.', '')],
                ['metric' => 'Recorded expenses (expense dates)', 'amount' => number_format($expenses, 2, '.', '')],
                ['metric' => 'Cash surplus / deficit (collections minus expenses)', 'amount' => number_format($collected - $expenses, 2, '.', '')],
            ];
            return [
                'columns' => ['metric' => 'Financial metric', 'amount' => 'PKR'],
                'rows' => $values,
                'note' => 'Booking value uses confirmed/completed bookings by booking date. Payments are received minus refunds by paid_at. Expenses use expense_date. Cash surplus is not accounting profit.',
            ];

        case 'bookings':
            // Query groups separately to avoid collation conflicts from SQL UNION.
            // Booking groups are one reservation; ungrouped bookings are one reservation each.
            $columns = [
                'reference' => 'Reference', 'customer' => 'Customer',
                'facility' => 'Facility', 'turf' => 'Turf',
                'date' => 'Booking date', 'start' => 'Start', 'end' => 'End',
                'source' => 'Source', 'status' => 'Status', 'amount' => 'PKR',
            ];
            $groupRows = tm_x_rows(
                $db,
                "SELECT CONCAT('Group #', g.id) AS reference, u.name AS customer,
                        f.name AS facility, t.name AS turf,
                        DATE(g.start_at) AS date,
                        g.start_at AS start, g.end_at AS end,
                        'online' AS source, g.status AS status,
                        g.total_amount AS amount
                 FROM tm_booking_groups g
                 JOIN users u ON u.id = g.customer_id
                 JOIN turfs t ON t.id = g.turf_id
                 JOIN facilities f ON f.id = t.facility_id
                 WHERE f.owner_id = ? AND f.deleted_at IS NULL
                   AND DATE(g.start_at) BETWEEN ? AND ? $facilityFilter
                 ORDER BY g.start_at DESC, g.id DESC",
                $byDate,
                $limit
            );
            $ungroupedRows = tm_x_rows(
                $db,
                "SELECT CONCAT('Booking #', b.id) AS reference, b.customer_name AS customer,
                        f.name AS facility, t.name AS turf,
                        b.booking_date AS date,
                        CONCAT(b.booking_date, ' ', b.start_time) AS start,
                        CONCAT(b.booking_date, ' ', b.end_time) AS end,
                        b.source AS source, b.status AS status,
                        b.total_amount AS amount
                 FROM bookings b
                 JOIN turfs t ON t.id = b.turf_id
                 JOIN facilities f ON f.id = t.facility_id
                 LEFT JOIN tm_booking_group_items gi ON gi.booking_id = b.id
                 WHERE f.owner_id = ? AND f.deleted_at IS NULL
                   AND gi.booking_id IS NULL
                   AND b.booking_date BETWEEN ? AND ? $facilityFilter
                 ORDER BY b.booking_date DESC, b.id DESC",
                $byDate,
                $limit
            );
            $rows = array_merge($groupRows, $ungroupedRows);
            usort($rows, static fn (array $a, array $b): int => strcmp((string) $b['start'], (string) $a['start']));
            return [
                'columns' => $columns,
                'rows' => array_slice($rows, 0, $limit),
                'note' => 'Grouped online bookings count once per reservation; standalone bookings are listed individually. Group statuses are read from tm_booking_groups.',
            ];

        case 'payments':
            return [
                'columns' => [
                    'id' => 'Payment ID', 'booking' => 'Booking ID',
                    'customer' => 'Customer', 'facility' => 'Facility',
                    'paid_at' => 'Payment time', 'method' => 'Method',
                    'status' => 'Status', 'amount' => 'PKR (signed)',
                ],
                'rows' => tm_x_rows(
                    $db,
                    "SELECT p.id, b.id AS booking, b.customer_name AS customer,
                            f.name AS facility, p.paid_at, p.method, p.status,
                            CASE WHEN p.status = 'refunded' THEN -p.amount ELSE p.amount END AS amount
                     FROM payments p
                     JOIN bookings b ON b.id = p.booking_id
                     JOIN turfs t ON t.id = b.turf_id
                     JOIN facilities f ON f.id = t.facility_id
                     WHERE f.owner_id = ? AND f.deleted_at IS NULL
                       AND p.paid_at >= ? AND p.paid_at < DATE_ADD(?, INTERVAL 1 DAY)
                       $facilityFilter
                     ORDER BY p.paid_at DESC, p.id DESC",
                    $byDate,
                    $limit
                ),
                'note' => 'Refunded payment rows show a negative amount; net collections are received payments minus refunds.',
            ];

        case 'expenses':
            return [
                'columns' => [
                    'id' => 'Expense ID', 'date' => 'Expense date',
                    'facility' => 'Facility', 'category' => 'Category',
                    'description' => 'Description', 'amount' => 'PKR',
                ],
                'rows' => tm_x_rows(
                    $db,
                    "SELECT e.id, e.expense_date AS date, f.name AS facility,
                            e.category, e.description, e.amount
                     FROM expenses e
                     JOIN facilities f ON f.id = e.facility_id
                     WHERE f.owner_id = ? AND f.deleted_at IS NULL
                       AND e.expense_date BETWEEN ? AND ? $facilityFilter
                     ORDER BY e.expense_date DESC, e.id DESC",
                    $byDate,
                    $limit
                ),
                'note' => 'Includes expenses explicitly recorded in Expenses Management. Maintenance-record costs are not added again.',
            ];

        case 'inventory':
            return [
                'columns' => [
                    'id' => 'Item ID', 'facility' => 'Facility', 'name' => 'Item',
                    'category' => 'Category', 'quantity' => 'Quantity',
                    'unit' => 'Unit', 'reorder_level' => 'Reorder level',
                    'unit_cost' => 'Unit cost (PKR)', 'stock_value' => 'Estimated value (PKR)',
                    'status' => 'Status',
                ],
                'rows' => tm_x_rows(
                    $db,
                    "SELECT i.id, f.name AS facility, i.name, i.category,
                            i.quantity, i.unit, i.reorder_level,
                            i.cost_per_unit AS unit_cost,
                            (i.quantity * COALESCE(i.cost_per_unit, 0)) AS stock_value,
                            i.status
                     FROM inventory_items i
                     JOIN facilities f ON f.id = i.facility_id
                     WHERE f.owner_id = ? AND f.deleted_at IS NULL $facilityFilter
                     ORDER BY f.name, i.name, i.id",
                    $byOwner,
                    $limit
                ),
                'note' => 'This is the CURRENT inventory snapshot, not a historical date-range report. Value = quantity multiplied by unit cost.',
            ];

        case 'stock':
            return [
                'columns' => [
                    'id' => 'Movement ID', 'date' => 'Timestamp',
                    'facility' => 'Facility', 'item' => 'Item',
                    'type' => 'Type', 'quantity_change' => 'Quantity change',
                    'unit' => 'Unit', 'notes' => 'Notes',
                ],
                'rows' => tm_x_rows(
                    $db,
                    "SELECT x.id, x.created_at AS date, f.name AS facility,
                            i.name AS item, x.transaction_type AS type,
                            x.quantity_change, i.unit, x.notes
                     FROM inventory_transactions x
                     JOIN inventory_items i ON i.id = x.item_id
                     JOIN facilities f ON f.id = i.facility_id
                     WHERE f.owner_id = ? AND f.deleted_at IS NULL
                       AND x.created_at >= ? AND x.created_at < DATE_ADD(?, INTERVAL 1 DAY)
                       $facilityFilter
                     ORDER BY x.created_at DESC, x.id DESC",
                    $byDate,
                    $limit
                ),
                'note' => 'Positive quantity changes add stock; negative changes remove stock.',
            ];

        case 'maintenance':
            return [
                'columns' => [
                    'id' => 'Maintenance ID', 'date' => 'Start date',
                    'end_date' => 'End date', 'facility' => 'Facility',
                    'turf' => 'Turf', 'description' => 'Description',
                    'status' => 'Status', 'cost' => 'Recorded cost (PKR)',
                ],
                'rows' => tm_x_rows(
                    $db,
                    "SELECT m.id, m.start_date AS date, m.end_date, f.name AS facility,
                            t.name AS turf, m.description, m.status, m.cost
                     FROM maintenance_records m
                     JOIN turfs t ON t.id = m.turf_id
                     JOIN facilities f ON f.id = t.facility_id
                     WHERE f.owner_id = ? AND f.deleted_at IS NULL
                       AND m.start_date BETWEEN ? AND ? $facilityFilter
                     ORDER BY m.start_date DESC, m.id DESC",
                    $byDate,
                    $limit
                ),
                'note' => 'Maintenance cost is recorded/planned cost, not necessarily paid spending. It is not added to the Expenses total.',
            ];
    }

    throw new LogicException('Unknown report type.');
}
